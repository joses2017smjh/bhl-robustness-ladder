"""Height fields for MuJoCo sim2sim evaluation on rough ground.

Training terrain (Isaac Lab) and evaluation terrain (MuJoCo) are generated by
completely different code, which is the point: if a policy only copes with the
exact height field it trained on, that is memorisation, not locomotion. What the
two share is the *physical envelope* -- amplitude, gradient, and obstacle height
are matched to the Isaac Lab sub-terrain menu in `bhl_robust.terrains.bumpy`, so
"difficulty 1.0" means roughly the same thing on both sides.

Difficulty is a single scalar so that terrain becomes a swept axis, exactly like
the DR ladder: evaluating one policy across d = 0 .. 1 yields a retention curve
rather than a single pass/fail.

Composition at difficulty d:
  * high-frequency noise    amplitude  0.05 * d      (matches noise_range)
  * low-frequency undulation amplitude 0.15 * d      (yields <= ~14 deg grades,
                                                      matching slope_range 0.26 rad)
  * discrete obstacles       height    0.04 * d      (matches obstacle_height_range)

d = 0 is exactly flat, so the same code path evaluates flat-ground policies and
the flat rung of the curve is not a special case.
"""

from __future__ import annotations

import numpy as np

# Physical extent of the generated patch, metres. The robot is re-centred each
# episode, so this only has to be large enough that a 10s rollout stays inside.
HALF_EXTENT = 12.0
# Peak-to-trough range the normalised [0,1] field is scaled into.
ELEVATION_M = 0.40
GRID = 257  # odd, so the exact centre is a sample point


def _smooth(a: np.ndarray, k: int) -> np.ndarray:
    """Cheap separable box blur; k must be odd."""
    if k <= 1:
        return a
    pad = k // 2
    p = np.pad(a, pad, mode="edge")
    c = np.cumsum(np.cumsum(p, axis=0), axis=1)
    c = np.pad(c, ((1, 0), (1, 0)))
    n = GRID
    out = (c[k:k + n, k:k + n] - c[0:n, k:k + n] - c[k:k + n, 0:n] + c[0:n, 0:n]) / (k * k)
    return out


def build_height_field(difficulty: float, seed: int = 0) -> np.ndarray:
    """Return elevation in METRES on a GRID x GRID lattice spanning the patch."""
    d = float(np.clip(difficulty, 0.0, 1.0))
    if d == 0.0:
        return np.zeros((GRID, GRID), dtype=np.float64)

    rng = np.random.default_rng(seed)
    xs = np.linspace(-HALF_EXTENT, HALF_EXTENT, GRID)
    X, Y = np.meshgrid(xs, xs, indexing="ij")

    # Low-frequency undulation: two incommensurate wavelengths so the surface
    # does not repeat over the rollout distance.
    phase = rng.uniform(0, 2 * np.pi, 4)
    undulation = (
        np.sin(2 * np.pi * X / 4.3 + phase[0]) * np.cos(2 * np.pi * Y / 5.1 + phase[1])
        + 0.6 * np.sin(2 * np.pi * X / 7.7 + phase[2]) * np.sin(2 * np.pi * Y / 6.3 + phase[3])
    )
    undulation *= 0.15 * d / 1.6   # normalise the summed amplitude

    # Broadband roughness, blurred slightly so it is walkable rather than
    # per-cell noise the contact solver would fight.
    noise = _smooth(rng.uniform(-1.0, 1.0, (GRID, GRID)), 3) * (0.05 * d)

    field = undulation + noise

    # Discrete obstacles: low, flat-topped blocks scattered outside the centre.
    n_obs = int(round(14 * d))
    cell = 2 * HALF_EXTENT / (GRID - 1)
    for _ in range(n_obs):
        w = rng.uniform(0.2, 0.6)
        cx, cy = rng.uniform(-HALF_EXTENT + 2, HALF_EXTENT - 2, 2)
        if abs(cx) < 1.2 and abs(cy) < 1.2:
            continue  # keep the spawn pad clear
        i0 = int((cx + HALF_EXTENT) / cell); j0 = int((cy + HALF_EXTENT) / cell)
        r = max(1, int(w / cell / 2))
        field[max(0, i0 - r):i0 + r, max(0, j0 - r):j0 + r] += 0.04 * d

    return field


def to_mujoco_data(field_m: np.ndarray) -> np.ndarray:
    """Normalise metres -> the [0,1] range MuJoCo's hfield_data expects."""
    lo = field_m.min()
    return np.clip((field_m - lo) / ELEVATION_M, 0.0, 1.0).astype(np.float64)


class HeightSampler:
    """Bilinear lookup of terrain height in world coordinates."""

    def __init__(self, field_m: np.ndarray):
        self.f = field_m
        self.offset = -field_m.min()   # MuJoCo shifts the field so min maps to 0

    def __call__(self, x: float, y: float) -> float:
        n = self.f.shape[0]
        u = (x + HALF_EXTENT) / (2 * HALF_EXTENT) * (n - 1)
        v = (y + HALF_EXTENT) / (2 * HALF_EXTENT) * (n - 1)
        u = min(max(u, 0.0), n - 1 - 1e-9)
        v = min(max(v, 0.0), n - 1 - 1e-9)
        i, j = int(u), int(v)
        du, dv = u - i, v - j
        h = (self.f[i, j] * (1 - du) * (1 - dv) + self.f[i + 1, j] * du * (1 - dv)
             + self.f[i, j + 1] * (1 - du) * dv + self.f[i + 1, j + 1] * du * dv)
        # Report height in the same frame MuJoCo renders the hfield in.
        return float(h + self.offset)
